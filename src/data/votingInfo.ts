// Curated state-level voting information.
// Strategy: hard-code the durable rules (voter ID category, no-excuse absentee y/n,
// early-voting y/n, online-registration y/n, automatic-registration y/n) and link out
// to each state's official Secretary of State / election division for the volatile
// stuff (exact deadlines, polling place lookup by address). This avoids the legal
// risk of stale dates while still giving users an immediate, useful page.
//
// Source: National Conference of State Legislatures (NCSL) + each state's official
// election website. Verified Q1 2026.

export type IdRequirement =
  | "strict-photo"
  | "non-strict-photo"
  | "strict-non-photo"
  | "non-strict-non-photo"
  | "no-id";

export interface StateVotingInfo {
  state: string;
  abbr: string;
  // Voter ID
  idRequirement: IdRequirement;
  idDescription: string;
  // Registration
  onlineRegistration: boolean;
  automaticRegistration: boolean;
  sameDayRegistration: boolean;
  registrationDeadlineRule: string; // human-readable rule (e.g. "15 days before election")
  // Absentee / Mail
  noExcuseAbsentee: boolean;
  absenteeNotes: string;
  // Early voting
  earlyVoting: boolean;
  earlyVotingNotes: string;
  // Official links
  sosName: string;
  sosUrl: string;
  registerUrl: string;
  pollingPlaceUrl: string;
  absenteeUrl: string;
}

const ID_LABELS: Record<IdRequirement, { label: string; tone: "ok" | "warn" | "strict" }> = {
  "strict-photo": { label: "Strict Photo ID required", tone: "strict" },
  "non-strict-photo": { label: "Photo ID requested (alternatives accepted)", tone: "warn" },
  "strict-non-photo": { label: "Strict ID required (photo not required)", tone: "warn" },
  "non-strict-non-photo": { label: "ID requested (alternatives accepted)", tone: "ok" },
  "no-id": { label: "No ID required", tone: "ok" },
};

export function getIdLabel(req: IdRequirement) {
  return ID_LABELS[req];
}

